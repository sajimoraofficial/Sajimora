struct Temp {
    path: PathBuf,
}

impl Temp {
    fn new(tag: &str) -> Self {
        let nanos = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let path = std::env::temp_dir().join(format!(
            "sajimora-impact-parity-{tag}-{}-{nanos}",
            std::process::id()
        ));
        fs::create_dir_all(path.join("workspace")).unwrap();
        Self { path }
    }

    fn repo(&self) -> PathBuf {
        let repo = self.path.join("workspace").join("repo");
        fs::create_dir_all(&repo).unwrap();
        git(&repo, &["init"]);
        git(&repo, &["config", "user.email", "fixture@example.invalid"]);
        git(&repo, &["config", "user.name", "Fixture"]);
        git(&repo, &["config", "core.autocrlf", "false"]);
        git(&repo, &["config", "commit.gpgsign", "false"]);
        repo
    }
}

impl Drop for Temp {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.path);
    }
}

fn git(repo: &Path, args: &[&str]) -> String {
    let output = Command::new("git")
        .arg("-C")
        .arg(repo)
        .args(args)
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "git {args:?}: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8_lossy(&output.stdout).trim().to_owned()
}

const PACKAGE_DIR: &str = "backend/src/main/java/com/example/demo";

fn fixture(tag: &str) -> (Temp, PathBuf) {
    let temp = Temp::new(tag);
    let repo = temp.repo();
    let sajimora = repo.join(".sajimora");
    fs::create_dir_all(&sajimora).unwrap();
    let manifest = json!({
        "manifestVersion": 1,
        "status": "COMPLETE",
        "roots": {
            "repo_root": repo.to_string_lossy().replace('\\', "/"),
            "backend_root": "backend",
            "frontend_root": null,
            "service_id": "user-service",
        },
    });
    fs::write(
        sajimora.join("init-manifest.json"),
        serde_json::to_string_pretty(&manifest).unwrap(),
    )
    .unwrap();

    let dir = repo.join(PACKAGE_DIR);
    fs::create_dir_all(&dir).unwrap();
    fs::write(
        dir.join("UserController.java"),
        r#"package com.example.demo;

import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

@RestController
@RequestMapping("/api/users")
public class UserController {

    @GetMapping
    public UserDto list() {
        return new UserDto();
    }
}
"#,
    )
    .unwrap();
    fs::write(
        dir.join("UserDto.java"),
        "package com.example.demo;\n\npublic class UserDto {\n    private Long id;\n    public Long getId() { return id; }\n}\n",
    )
    .unwrap();
    git(&repo, &["add", "-A"]);
    git(&repo, &["commit", "-m", "baseline"]);

    // Unstaged contract change plus consumer evidence and generated tests.
    fs::write(
        dir.join("UserDto.java"),
        "package com.example.demo;\n\npublic class UserDto {\n    private Long id;\n    private String email;\n    public Long getId() { return id; }\n    public String getEmail() { return email; }\n}\n",
    )
    .unwrap();
    fs::write(sajimora.join("frontend-contract.json"), consumer_artifact()).unwrap();
    let test_file = repo.join("tests/UserContractTest.java");
    fs::create_dir_all(test_file.parent().unwrap()).unwrap();
    fs::write(
        &test_file,
        "// Generated by Sajimora Native Synthesis (JUnit 5)\n\nclass UserContractTest {\n    // [CONTRACT_TEST] Verified contract constraints for GET /api/users\n}\n",
    )
    .unwrap();
    (temp, repo)
}

#[test]
fn cli_file_and_mcp_response_are_byte_identical() {
    let (temp, repo) = fixture("bytes");
    let out = temp.path.join("workspace/report.json");
    let test_file = repo.join("tests/UserContractTest.java");

    let cli = Command::new(env!("CARGO_BIN_EXE_sajimora"))
        .args([
            "endpoint-impact",
            "--repo",
            repo.to_str().unwrap(),
            "--generated-tests",
            test_file.to_str().unwrap(),
            "--out",
            out.to_str().unwrap(),
        ])
        .output()
        .unwrap();
    assert!(
        cli.status.success(),
        "cli stderr: {}",
        String::from_utf8_lossy(&cli.stderr)
    );
    let cli_text = fs::read_to_string(&out).unwrap();
    assert!(cli_text.starts_with("{\n  \"schemaVersion\": \"SAJIMORA_ENDPOINT_IMPACT_V1\""));
    assert!(
        !repo.join(".sajimora/impact-report.json").exists(),
        "the legacy report name must never be written"
    );

    let args = json!({
        "repoRoot": repo.to_string_lossy(),
        "mode": "workingTreeVsHead",
        "generatedTests": [test_file.to_string_lossy()],
    });
    let mcp_text = sajimora_mcp::endpoint_impact::run_endpoint_impact(
        &[temp.path.clone()],
        args.as_object().unwrap(),
    )
    .unwrap();
    assert_eq!(
        mcp_text, cli_text,
        "CLI and MCP must render identical reports"
    );

    // Repeating either surface over an unchanged tree must render the same bytes.
    let mcp_again = sajimora_mcp::endpoint_impact::run_endpoint_impact(
        &[temp.path.clone()],
        args.as_object().unwrap(),
    )
    .unwrap();
    assert_eq!(
        mcp_again, mcp_text,
        "repeated analysis must be deterministic"
    );
    let out_again = temp.path.join("workspace/report-again.json");
    let cli_again = Command::new(env!("CARGO_BIN_EXE_sajimora"))
        .args([
            "endpoint-impact",
            "--repo",
            repo.to_str().unwrap(),
            "--generated-tests",
            test_file.to_str().unwrap(),
            "--out",
            out_again.to_str().unwrap(),
        ])
        .output()
        .unwrap();
    assert!(cli_again.status.success());
    assert_eq!(fs::read_to_string(&out_again).unwrap(), cli_text);

    let default_args = json!({ "repoRoot": repo.to_string_lossy() });
    let default_text = sajimora_mcp::endpoint_impact::run_endpoint_impact(
        &[temp.path.clone()],
        default_args.as_object().unwrap(),
    )
    .unwrap();
    let report: Value = serde_json::from_str(&default_text).unwrap();
    assert_eq!(report["summary"]["changedFiles"], 1);
    assert_eq!(report["summary"]["affectedEndpoints"], 1);
    assert_eq!(report["endpoints"][0]["consumers"][0]["rule"], "EXACT");
}

