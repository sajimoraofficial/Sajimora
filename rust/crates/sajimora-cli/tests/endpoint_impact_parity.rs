#[test]
fn mcp_rejects_paths_outside_the_allowed_roots() {
    let (temp, repo) = fixture("escape");
    let other = Temp::new("other");

    let outside_repo = json!({ "repoRoot": temp.path.to_string_lossy() });
    let error = sajimora_mcp::endpoint_impact::run_endpoint_impact(
        &[other.path.clone()],
        outside_repo.as_object().unwrap(),
    )
    .unwrap_err();
    assert!(
        format!("{error:#}").contains("outside all allowed roots"),
        "unexpected error: {error:#}"
    );

    let outside_output = json!({
        "repoRoot": repo.to_string_lossy(),
        "outputPath": other.path.join("report.json").to_string_lossy(),
    });
    assert!(sajimora_mcp::endpoint_impact::run_endpoint_impact(
        &[temp.path.clone()],
        outside_output.as_object().unwrap(),
    )
    .is_err());

    let outside_tests = json!({
        "repoRoot": repo.to_string_lossy(),
        "generatedTests": [other.path.join("Test.java").to_string_lossy()],
    });
    assert!(sajimora_mcp::endpoint_impact::run_endpoint_impact(
        &[temp.path.clone()],
        outside_tests.as_object().unwrap(),
    )
    .is_err());

    drop(other);
}

#[test]
fn mcp_output_path_rules_and_relative_resolution() {
    let (temp, repo) = fixture("output");

    let legacy = json!({
        "repoRoot": repo.to_string_lossy(),
        "outputPath": "impact-report.json",
    });
    let error = sajimora_mcp::endpoint_impact::run_endpoint_impact(
        &[temp.path.clone()],
        legacy.as_object().unwrap(),
    )
    .unwrap_err();
    assert!(format!("{error:#}").contains("reserved"));

    let escape = json!({
        "repoRoot": repo.to_string_lossy(),
        "outputPath": "../escape.json",
    });
    assert!(sajimora_mcp::endpoint_impact::run_endpoint_impact(
        &[temp.path.clone()],
        escape.as_object().unwrap(),
    )
    .is_err());

    let missing_parent = json!({
        "repoRoot": repo.to_string_lossy(),
        "outputPath": "missing/report.json",
    });
    assert!(sajimora_mcp::endpoint_impact::run_endpoint_impact(
        &[temp.path.clone()],
        missing_parent.as_object().unwrap(),
    )
    .is_err());

    let relative = json!({
        "repoRoot": repo.to_string_lossy(),
        "outputPath": ".sajimora/endpoint-impact.json",
    });
    let text = sajimora_mcp::endpoint_impact::run_endpoint_impact(
        &[temp.path.clone()],
        relative.as_object().unwrap(),
    )
    .unwrap();
    let written = fs::read_to_string(repo.join(".sajimora/endpoint-impact.json")).unwrap();
    assert_eq!(written, text);
}

#[test]
fn base_and_candidate_flags_match_the_commit_range_flag() {
    let (temp, repo) = fixture("range-flags");
    let baseline = git(&repo, &["rev-parse", "HEAD"]);
    git(&repo, &["add", "backend"]);
    git(&repo, &["commit", "-m", "change the contract"]);
    let ranged = temp.path.join("workspace/ranged.json");
    let split = temp.path.join("workspace/split.json");

    let run = |extra: &[&str], out: &Path| {
        let mut args = vec![
            "endpoint-impact".to_string(),
            "--repo".to_string(),
            repo.to_string_lossy().into_owned(),
            "--out".to_string(),
            out.to_string_lossy().into_owned(),
        ];
        args.extend(extra.iter().map(|value| value.to_string()));
        Command::new(env!("CARGO_BIN_EXE_sajimora"))
            .args(&args)
            .output()
            .unwrap()
    };

    let range_arg = format!("{baseline}..HEAD");
    let via_range = run(
        &["--mode", "commitRange", "--commit-range", &range_arg],
        &ranged,
    );
    assert!(
        via_range.status.success(),
        "stderr: {}",
        String::from_utf8_lossy(&via_range.stderr)
    );
    let via_flags = run(
        &[
            "--mode",
            "commitRange",
            "--base",
            &baseline,
            "--candidate",
            "HEAD",
        ],
        &split,
    );
    assert!(
        via_flags.status.success(),
        "stderr: {}",
        String::from_utf8_lossy(&via_flags.stderr)
    );
    assert_eq!(
        fs::read_to_string(&ranged).unwrap(),
        fs::read_to_string(&split).unwrap(),
        "--base/--candidate must compose the same range as --commit-range"
    );

    let lone_base = run(&["--mode", "commitRange", "--base", &baseline], &split);
    assert_eq!(lone_base.status.code(), Some(2));
    assert!(
        String::from_utf8_lossy(&lone_base.stderr).contains("--candidate"),
        "stderr: {}",
        String::from_utf8_lossy(&lone_base.stderr)
    );

    let wrong_mode = run(&["--base", &baseline, "--candidate", "HEAD"], &split);
    assert_eq!(wrong_mode.status.code(), Some(2));
    assert!(
        String::from_utf8_lossy(&wrong_mode.stderr).contains("--mode commitRange"),
        "stderr: {}",
        String::from_utf8_lossy(&wrong_mode.stderr)
    );
}

