struct GenMarker {
    file: String,
    line: u64,
    kind: &'static str,
    method: String,
    route: String,
}

struct TestReport {
    by_endpoint: BTreeMap<String, Vec<Value>>,
    files: Vec<Value>,
    not_generated: Vec<String>,
    marker_count: usize,
}

fn resolve_test_paths(
    repo_root: &Path,
    allowed_roots: &[PathBuf],
    requested: &[PathBuf],
) -> Result<Vec<PathBuf>> {
    let mut resolved = Vec::new();
    let mut seen = BTreeSet::new();
    for path in requested {
        let joined = if path.is_absolute() {
            path.clone()
        } else {
            repo_root.join(path)
        };
        let confined = confine(&joined, allowed_roots)
            .with_context(|| format!("Cannot resolve generated test file {:?}", path))?;
        if seen.insert(confined.clone()) {
            resolved.push(confined);
        }
    }
    Ok(resolved)
}

fn read_generated_tests(
    repo_root: &Path,
    paths: &[PathBuf],
    affected: &[Affected],
) -> Result<TestReport> {
    let mut report = TestReport {
        by_endpoint: BTreeMap::new(),
        files: Vec::new(),
        not_generated: Vec::new(),
        marker_count: 0,
    };
    let supported: BTreeSet<(String, String)> = affected
        .iter()
        .map(|entry| (entry.method.clone(), entry.route.clone()))
        .collect();

    for path in paths {
        let display = display_path(repo_root, path);
        let bytes = read_bounded(path, MAX_TEST_FILE_BYTES)
            .with_context(|| format!("Cannot read generated test file {display}"))?;
        let digest = hex::encode(Sha256::digest(&bytes));
        let text = String::from_utf8_lossy(&bytes);
        let generated = text.lines().any(|line| line.contains(GENERATED_HEADER));
        let mut markers = Vec::new();
        if generated {
            for (index, line) in text.lines().enumerate() {
                if let Some(marker) = parse_marker(line.trim()) {
                    markers.push(GenMarker {
                        file: display.clone(),
                        line: index as u64 + 1,
                        kind: marker.kind,
                        method: marker.method,
                        route: marker.route,
                    });
                }
            }
        } else {
            report.not_generated.push(display.clone());
        }
        for marker in &markers {
            if supported.contains(&(marker.method.clone(), marker.route.clone())) {
                report.marker_count += 1;
                let entry = json!({
                    "file": marker.file,
                    "line": marker.line,
                    "kind": marker.kind,
                });
                report
                    .by_endpoint
                    .entry(format!("{} {}", marker.method, marker.route))
                    .or_default()
                    .push(entry);
            }
        }
        report.files.push(json!({
            "path": display,
            "sha256": digest,
            "generated": generated,
            "markers": markers.len(),
        }));
    }

    for bucket in report.by_endpoint.values_mut() {
        bucket.sort_by_key(|record| {
            (
                record["file"].as_str().unwrap_or_default().to_string(),
                record["line"].as_u64().unwrap_or(0),
                record["kind"].as_str().unwrap_or_default().to_string(),
            )
        });
    }
    report
        .files
        .sort_by_key(|record| record["path"].as_str().unwrap_or_default().to_string());
    Ok(report)
}

struct ParsedMarker {
    kind: &'static str,
    method: String,
    route: String,
}

fn parse_marker(line: &str) -> Option<ParsedMarker> {
    const ABSTAIN: (&str, &str) = (
        "// ABSTAIN: Endpoint ",
        " contains unresolved WireType::Unknown",
    );
    const ADVISORY: (&str, &str) = (
        "// [ADVISORY_FALLBACK_TEST] Endpoint ",
        " contains dynamic/wildcard payload (Any); verifying route and status",
    );
    const CONTRACT: &str = "// [CONTRACT_TEST] Verified contract constraints for ";
    const SHAPE: (&str, &str) = ("// Shape of the ", " response");

    let (kind, text) = if let Some(text) = line
        .strip_prefix(ABSTAIN.0)
        .and_then(|rest| rest.strip_suffix(ABSTAIN.1))
    {
        ("ABSTAINED", text)
    } else if let Some(text) = line
        .strip_prefix(ADVISORY.0)
        .and_then(|rest| rest.strip_suffix(ADVISORY.1))
    {
        ("ADVISORY_FALLBACK_TEST", text)
    } else if let Some(text) = line.strip_prefix(CONTRACT) {
        ("CONTRACT_TEST", text)
    } else if let Some(text) = line
        .strip_prefix(SHAPE.0)
        .and_then(|rest| rest.strip_suffix(SHAPE.1))
    {
        ("SHAPE_CHECK", text)
    } else {
        return None;
    };
    let (method, route) = text.split_once(' ')?;
    if method.is_empty() || !route.starts_with('/') {
        return None;
    }
    Some(ParsedMarker {
        kind,
        method: method.to_uppercase(),
        route: route.to_string(),
    })
}

