fn layer(reasons: Vec<Value>) -> Value {
    json!({
        "complete": reasons.is_empty(),
        "reasons": reasons,
    })
}

fn reason(code: &str, detail: &str, extra: Value) -> Value {
    let mut record = Map::new();
    record.insert("code".to_string(), json!(code));
    record.insert("detail".to_string(), json!(detail));
    if let Value::Object(extra) = extra {
        for (key, value) in extra {
            record.insert(key, value);
        }
    }
    Value::Object(record)
}

/// A flat, deterministic index of every missing-evidence code in the report.
/// Layer reasons and provider extraction blockers share this shape, so a
/// consumer never has to know where each code was recorded.
fn reason_index(
    layers: &[(&str, &Value)],
    extracted: Option<&(ContractArtifactEnvelope, ContractArtifactEnvelope)>,
) -> Vec<Value> {
    let mut entries: BTreeMap<(String, String), (usize, String)> = BTreeMap::new();
    let mut record = |code: &str, layer: &str, detail: &str| {
        let entry = entries
            .entry((code.to_string(), layer.to_string()))
            .or_insert((0, detail.to_string()));
        entry.0 += 1;
    };
    for (layer_name, block) in layers {
        for item in block["reasons"].as_array().into_iter().flatten() {
            if let Some(code) = item["code"].as_str() {
                record(
                    code,
                    layer_name,
                    item["detail"].as_str().unwrap_or_default(),
                );
            }
        }
    }
    if let Some((base_env, candidate_env)) = extracted {
        for envelope in [base_env, candidate_env] {
            for blocker in &envelope.completeness.blockers {
                record(&blocker.code, "provider", &blocker.message);
            }
        }
    }
    entries
        .into_iter()
        .map(|((code, layer), (count, detail))| {
            json!({
                "code": code,
                "layer": layer,
                "count": count,
                "detail": detail,
            })
        })
        .collect()
}

fn confine(path: &Path, allowed_roots: &[PathBuf]) -> Result<PathBuf> {
    if allowed_roots.is_empty() {
        normalize_path(path)
    } else {
        validate_path_under_roots(path, allowed_roots)
    }
}

fn display_path(repo_root: &Path, path: &Path) -> String {
    let display = path
        .strip_prefix(repo_root)
        .map(|relative| relative.to_string_lossy().replace('\\', "/"))
        .unwrap_or_else(|_| path.to_string_lossy().replace('\\', "/"));
    if display.is_empty() {
        ".".to_string()
    } else {
        display
    }
}
