fn is_extraction_input(
    backend: &BackendScope,
    provider: ProviderKind,
    contract_sources: &BTreeSet<String>,
    repo_path: &str,
) -> bool {
    if provider == ProviderKind::Spring && repo_path == "lombok.config" {
        return true;
    }
    if (provider == ProviderKind::Spring || provider == ProviderKind::JaxRs)
        && repo_path.ends_with(".java")
        && contract_sources.contains(repo_path)
        && !is_excluded_source_path(repo_path)
    {
        return true;
    }
    let Some(scoped) = backend.within(repo_path) else {
        return false;
    };
    match provider {
        ProviderKind::Spring | ProviderKind::JaxRs => {
            if scoped.ends_with(".java") {
                return !is_excluded_source_path(&scoped);
            }
            config_tails().iter().any(|tail| *tail == scoped)
                || is_profile_config_path(&scoped)
                || scoped == "lombok.config"
        }
        ProviderKind::NestJs => is_provider_ts_file(&scoped),
        ProviderKind::NextJs => crate::nextjs_routes::is_nextjs_route_file(&scoped),
        ProviderKind::Express => crate::express_routes::is_express_source_file(&scoped),
        ProviderKind::FileRouter => crate::file_system_routes::is_file_router_source_file(&scoped),
    }
}

fn extract_sides(
    repo: &Path,
    backend: &BackendScope,
    provider: ProviderKind,
    service_id: &str,
    sides: &Sides,
    contract_sources: &BTreeSet<String>,
    slice_filter: Option<&BTreeSet<String>>,
) -> Result<(ContractArtifactEnvelope, ContractArtifactEnvelope)> {
    let entries = |listing: &Listing| -> Vec<(String, String, Option<u64>)> {
        listing
            .0
            .iter()
            .filter(|(path, _)| is_extraction_input(backend, provider, contract_sources, path))
            .filter(|(path, _)| match slice_filter {
                Some(slice) => slice.contains(path.as_str()) || path.ends_with("lombok.config"),
                None => true,
            })
            .map(|(path, entry)| (path.clone(), entry.oid.clone(), entry.size))
            .collect()
    };
    let base = revision::extract_listing(
        repo,
        backend,
        service_id,
        entries(&sides.base),
        ListingSource::GitObjects,
        &sides.base_id.1,
        &sides.base_id.1,
    )
    .context("Extracting the base revision failed")?;
    let candidate = revision::extract_listing(
        repo,
        backend,
        service_id,
        entries(&sides.candidate),
        sides.candidate_source,
        &sides.base_id.1,
        &sides.candidate_id.1,
    )
    .context("Extracting the candidate revision failed")?;
    Ok((base, candidate))
}

fn extraction_completeness(envelope: &ContractArtifactEnvelope) -> Value {
    let mut codes: BTreeSet<&str> = BTreeSet::new();
    for blocker in &envelope.completeness.blockers {
        codes.insert(blocker.code.as_str());
    }
    json!({
        "complete": envelope.completeness.complete,
        "unresolvedEndpoints": envelope.completeness.unresolved_endpoints.len(),
        "blockerCount": envelope.completeness.blockers.len(),
        "blockerCodes": codes.into_iter().collect::<Vec<_>>(),
    })
}

