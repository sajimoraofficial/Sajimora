//! endpoint_impact.rs — advisory change-to-endpoint impact from recorded provenance.
//!
//! Given a change set between two revisions (working tree vs HEAD, index vs HEAD,
//! or two commits), re-extract the provider contract on both sides, group the
//! endpoints, and attribute changes to the source files each endpoint records in
//! its provenance. Consumer call sites come from sealed frontend artifacts that
//! pass their own integrity check and are linked by the comparison engine's
//! rules; generated tests are read from files the caller names and matched only
//! on the synthesis markers they contain.
//!
//! Nothing here selects tests or blocks a merge. Every layer that cannot be
//! proved complete says so, and a link is never inferred from a path, a branch
//! name, or a directory layout.
//!
//! The sealed baseline records no revision, so the base side is re-extracted
//! rather than read from `.sajimora/`. Working-tree analysis lists `HEAD` and the
//! index through the existing revision reader (`git ls-tree`/`ls-files`); it never
//! runs `git diff` or `git status`, so no repository-configured filter, textconv
//! driver, or fsmonitor hook can change what is analyzed.

