struct ConsumerReport {
    by_endpoint: BTreeMap<String, Vec<Value>>,
    artifacts: Vec<Value>,
    rejected: Vec<Value>,
    non_consumer: Vec<Value>,
    reasons: Vec<Value>,
    admitted_artifacts: usize,
    linked: usize,
    unlinkable: Vec<String>,
    traversal_incomplete: Vec<String>,
    target_mismatches: Vec<String>,
}

fn collect_consumers(
    allowed_roots: &[PathBuf],
    repo_root: &Path,
    affected: &[Affected],
    base_endpoints: &BTreeMap<String, SideEndpoint<'_>>,
    candidate_endpoints: &BTreeMap<String, SideEndpoint<'_>>,
    extracted: Option<&(ContractArtifactEnvelope, ContractArtifactEnvelope)>,
) -> Result<ConsumerReport> {
    let mut report = ConsumerReport {
        by_endpoint: BTreeMap::new(),
        artifacts: Vec::new(),
        rejected: Vec::new(),
        non_consumer: Vec::new(),
        reasons: Vec::new(),
        admitted_artifacts: 0,
        linked: 0,
        unlinkable: Vec::new(),
        traversal_incomplete: Vec::new(),
        target_mismatches: Vec::new(),
    };

    // Fast-path: Check verified contract artifact cache in SQLite contracts.db
    let db_path = repo_root
        .join(".sajimora")
        .join(crate::contracts_db::CONTRACTS_DB_NAME);
    let own_frontend = repo_root.join(".sajimora").join("frontend-contract.json");
    if db_path.exists() && own_frontend.exists() {
        if let Ok(conn) = crate::contracts_db::open_reader(&db_path) {
            if let Ok(artifact_cache) = crate::contracts_db::load_artifact_cache(&conn) {
                let norm_path = own_frontend.to_string_lossy().replace('\\', "/");
                if let Some(cached) = artifact_cache.get(&norm_path) {
                    let meta = fs::symlink_metadata(&own_frontend).ok();
                    let cur_size = meta.as_ref().map(|m| m.len()).unwrap_or(0);
                    let cur_mtime = meta
                        .as_ref()
                        .and_then(|m| m.modified().ok())
                        .and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok())
                        .map(|d| d.as_nanos())
                        .unwrap_or(0);
                    if cur_size == cached.size && cur_mtime == cached.mtime_nanos {
                        let display = display_path(repo_root, &own_frontend);
                        if !cached.integrity_valid {
                            report.rejected.push(json!({
                                "path": display,
                                "step": cached.step,
                                "reason": "artifact integrity digest does not match its contents",
                            }));
                            report.reasons.push(reason(
                                "REJECTED_CONSUMER_CONTRACT",
                                "A discovered consumer artifact could not be admitted, so its call sites are missing from this report.",
                                json!({ "detail": format!("{display}: artifact integrity digest does not match its contents") }),
                            ));
                            return Ok(report);
                        }
                        report.admitted_artifacts = 1;
                        report.artifacts.push(json!({
                            "path": display,
                            "step": cached.step,
                            "serviceId": cached.service_id,
                            "sha256": cached.sha256,
                            "clientContracts": cached.client_contracts_count,
                            "complete": cached.complete,
                        }));
                        if !cached.complete {
                            report.reasons.push(reason(
                                "CONSUMER_ARTIFACT_INCOMPLETE",
                                "A consumer artifact marks its own extraction as incomplete; call sites inside it may be partial.",
                                json!({ "artifacts": [display] }),
                            ));
                        }

                        if affected.is_empty() {
                            return Ok(report);
                        }

                        for entry in affected {
                            let norm_route = crate::contracts_db::canonical_route_key(&entry.route);
                            if let Ok(matches) = crate::contracts_db::query_consumers_by_route(
                                &conn,
                                &norm_route,
                                Some(&entry.method),
                            ) {
                                for m in matches {
                                    report.linked += 1;
                                    let call_sites = if !m.call_site_usage.is_empty() {
                                        vec![json!({
                                            "file": m.source_file,
                                            "line": m.source_line,
                                            "column": 0,
                                            "usage": m.call_site_usage,
                                        })]
                                    } else {
                                        Vec::new()
                                    };
                                    let record = json!({
                                        "artifact": display,
                                        "artifactServiceId": m.service_id,
                                        "sourceFile": m.source_file,
                                        "sourceLine": m.source_line,
                                        "method": m.http_method.to_uppercase(),
                                        "route": m.normalized_route,
                                        "rule": "EXACT",
                                        "heuristic": false,
                                        "unverifiedRouteConstraint": serde_json::Value::Null,
                                        "targetServiceId": m.service_id,
                                        "decoderKind": "JSON",
                                        "callSites": call_sites,
                                    });
                                    let bucket =
                                        report.by_endpoint.entry(entry.key.clone()).or_default();
                                    bucket.push(record);
                                }
                            }
                        }
                        return Ok(report);
                    }
                }
            }
        }
    }

    let discovery = match discover(repo_root, allowed_roots) {
        Ok(discovery) => discovery,
        Err(error) => {
            report.reasons.push(reason(
                "CONSUMER_DISCOVERY_FAILED",
                "Consumer contract discovery failed; no call site could be linked.",
                json!({ "detail": error.to_string() }),
            ));
            return Ok(report);
        }
    };

    for rejected in &discovery.rejected {
        report.rejected.push(json!({
            "path": display_path(repo_root, &rejected.path),
            "step": rejected.step,
            "reason": rejected.reason,
        }));
    }
    let mut rejected_reasons: Vec<String> = discovery
        .rejected
        .iter()
        .map(|rejected| {
            format!(
                "{}: {}",
                display_path(repo_root, &rejected.path),
                rejected.reason
            )
        })
        .collect();
    rejected_reasons.sort();

    let supported_methods: BTreeSet<&str> =
        affected.iter().map(|entry| entry.method.as_str()).collect();

    for (discovered, envelope) in &discovery.contracts {
        let display = display_path(repo_root, &discovered.path);
        match verify_envelope_integrity(envelope) {
            Ok(true) => {}
            Ok(false) => {
                rejected_reasons.push(format!(
                    "{display}: artifact integrity digest does not match its contents"
                ));
                report.rejected.push(json!({
                    "path": display,
                    "step": discovered.step,
                    "reason": "artifact integrity digest does not match its contents",
                }));
                continue;
            }
            Err(error) => {
                rejected_reasons.push(format!("{display}: {error}"));
                report.rejected.push(json!({
                    "path": display,
                    "step": discovered.step,
                    "reason": error.to_string(),
                }));
                continue;
            }
        }
        let payload = match &envelope.payload {
            ArtifactPayload::Frontend(payload) => payload,
            ArtifactPayload::Backend(_) => {
                report.non_consumer.push(json!({
                    "path": display,
                    "step": discovered.step,
                    "serviceId": discovered.service_id,
                    "reason": "artifact carries a provider payload, not consumer contracts",
                }));
                continue;
            }
        };
        report.admitted_artifacts += 1;
        let mut incomplete = false;
        if !envelope.completeness.complete {
            incomplete = true;
        }
        report.artifacts.push(json!({
            "path": display,
            "step": discovered.step,
            "serviceId": discovered.service_id,
            "sha256": discovered.sha256,
            "clientContracts": payload.client_contracts.len(),
            "complete": envelope.completeness.complete,
        }));
        if incomplete {
            report.reasons.push(reason(
                "CONSUMER_ARTIFACT_INCOMPLETE",
                "A consumer artifact marks its own extraction as incomplete; call sites inside it may be partial.",
                json!({ "artifacts": [display] }),
            ));
        }

        for client in &payload.client_contracts {
            if !supported_methods.contains(client.http_method.to_uppercase().as_str()) {
                continue;
            }
            let mut linked = None;
            let mut skipped = None;
            for (side_key, side_map) in
                [("candidate", candidate_endpoints), ("base", base_endpoints)]
            {
                let Some(envelope) = extracted.map(|(base, candidate)| match side_key {
                    "candidate" => candidate,
                    _ => base,
                }) else {
                    continue;
                };
                for entry in affected {
                    if entry.method != client.http_method.to_uppercase() {
                        continue;
                    }
                    let Some(side) = side_map.get(&entry.key) else {
                        continue;
                    };
                    let Some(endpoint) = side.contracts.first() else {
                        continue;
                    };
                    match link_client_to_endpoint(client, endpoint, envelope, false) {
                        ClientLink::Linked {
                            rule,
                            unverified_constraint,
                        } => {
                            linked = Some((entry, rule, unverified_constraint));
                            break;
                        }
                        ClientLink::Blocked(block) => {
                            skipped = Some(block);
                        }
                        ClientLink::NotLinked => {}
                    }
                }
                if linked.is_some() {
                    break;
                }
            }

            let client_label = format!(
                "{display}:{}:{} {} {}",
                client.source_file, client.source_line, client.http_method, client.normalized_route
            );

            match linked {
                Some((entry, rule, unverified_constraint)) => {
                    report.linked += 1;
                    let consumers = client
                        .consumers
                        .iter()
                        .map(|site| {
                            json!({
                                "file": site.file,
                                "line": site.line,
                                "column": site.column,
                                "usage": site.usage,
                            })
                        })
                        .collect::<Vec<_>>();
                    let record = json!({
                        "artifact": display,
                        "artifactServiceId": discovered.service_id,
                        "sourceFile": client.source_file,
                        "sourceLine": client.source_line,
                        "method": client.http_method.to_uppercase(),
                        "route": client.normalized_route,
                        "rule": rule.label(),
                        "heuristic": rule != RouteLinkRule::Exact,
                        "unverifiedRouteConstraint": unverified_constraint,
                        "targetServiceId": client.target_service_id,
                        "decoderKind": client.decoder_kind,
                        "callSites": consumers,
                    });
                    let key = contract_core::canonical::canonical_json(&record);
                    let bucket = report.by_endpoint.entry(entry.key.clone()).or_default();
                    if !bucket
                        .iter()
                        .any(|existing| contract_core::canonical::canonical_json(existing) == key)
                    {
                        bucket.push(record);
                    }
                    if client.consumer_traversal_complete == Some(false) {
                        report.traversal_incomplete.push(client_label.clone());
                    }
                }
                None => match skipped {
                    Some(block) => {
                        let text = format!("{client_label} ({})", block.reason());
                        match block {
                            ClientLinkBlock::TargetServiceMismatch
                            | ClientLinkBlock::TargetApiVersionMismatch => {
                                report.target_mismatches.push(text)
                            }
                            ClientLinkBlock::UndeclaredAbsoluteUrl
                            | ClientLinkBlock::RelativeRouteWithoutTargetService => {
                                report.unlinkable.push(text)
                            }
                        }
                    }
                    None => {
                        if route_has_unresolved_placeholder(&client.normalized_route) {
                            report.unlinkable.push(format!(
                                "{client_label} (consumer route contains an unresolved interpolation placeholder)"
                            ));
                        }
                    }
                },
            }
        }
    }

    report.unlinkable.sort();
    report.traversal_incomplete.sort();
    report.target_mismatches.sort();
    for bucket in report.by_endpoint.values_mut() {
        bucket.sort_by_key(|record| {
            (
                record["artifact"].as_str().unwrap_or_default().to_string(),
                record["sourceFile"]
                    .as_str()
                    .unwrap_or_default()
                    .to_string(),
                record["sourceLine"].as_u64().unwrap_or(0),
                record["route"].as_str().unwrap_or_default().to_string(),
            )
        });
    }
    report
        .artifacts
        .sort_by_key(|record| record["path"].as_str().unwrap_or_default().to_string());
    report
        .rejected
        .sort_by_key(|record| record["path"].as_str().unwrap_or_default().to_string());
    report
        .non_consumer
        .sort_by_key(|record| record["path"].as_str().unwrap_or_default().to_string());
    rejected_reasons.sort();
    rejected_reasons.dedup();
    report.reasons.extend(rejected_reasons.into_iter().map(|detail| {
        reason(
            "REJECTED_CONSUMER_CONTRACT",
            "A discovered consumer artifact could not be admitted, so its call sites are missing from this report.",
            json!({ "detail": detail }),
        )
    }));
    Ok(report)
}

fn route_has_unresolved_placeholder(route: &str) -> bool {
    route.split('/').any(|segment| segment.contains(":param"))
}

