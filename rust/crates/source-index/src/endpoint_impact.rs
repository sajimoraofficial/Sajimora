#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ImpactMode {
    WorkingTree,
    Staged,
    CommitRange,
}

impl ImpactMode {
    pub fn parse(raw: &str) -> Result<Self> {
        match raw {
            "workingTreeVsHead" => Ok(ImpactMode::WorkingTree),
            "stagedVsHead" => Ok(ImpactMode::Staged),
            "commitRange" => Ok(ImpactMode::CommitRange),
            other => bail!(
                "Unknown impact mode {other:?}; expected workingTreeVsHead, stagedVsHead, or commitRange"
            ),
        }
    }

    pub fn label(self) -> &'static str {
        match self {
            ImpactMode::WorkingTree => "workingTreeVsHead",
            ImpactMode::Staged => "stagedVsHead",
            ImpactMode::CommitRange => "commitRange",
        }
    }
}

#[derive(Debug, Clone)]
pub struct ImpactRequest {
    pub repo_root: PathBuf,
    pub mode: ImpactMode,
    pub commit_range: Option<String>,
    pub generated_tests: Vec<PathBuf>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PrescriptiveFix {
    pub dto: String,
    pub file: String,
    pub suggested_fix: String,
    pub recommendation: String,
}

fn detect_prescriptive_fixes(
    base_pool: Option<&BTreeMap<String, WireType>>,
    cand_pool: Option<&BTreeMap<String, WireType>>,
    changed_files: &BTreeSet<String>,
) -> Vec<PrescriptiveFix> {
    let mut fixes = Vec::new();
    let (Some(base_types), Some(cand_types)) = (base_pool, cand_pool) else {
        return fixes;
    };

    for (type_name, base_wire) in base_types {
        let Some(cand_wire) = cand_types.get(type_name) else {
            continue;
        };
        let (WireType::Object(base_obj), WireType::Object(cand_obj)) = (base_wire, cand_wire)
        else {
            continue;
        };

        let file = base_obj
            .provenance
            .as_ref()
            .map(|p| p.file.clone())
            .or_else(|| cand_obj.provenance.as_ref().map(|p| p.file.clone()))
            .unwrap_or_default();

        if !file.is_empty() && !changed_files.contains(&file) {
            continue;
        }

        let base_props: BTreeSet<String> = base_obj
            .properties
            .iter()
            .map(|p| p.wire_name.clone())
            .collect();
        let cand_props: BTreeSet<String> = cand_obj
            .properties
            .iter()
            .map(|p| p.wire_name.clone())
            .collect();

        let removed_props: Vec<String> = base_props.difference(&cand_props).cloned().collect();
        let added_props: Vec<String> = cand_props.difference(&base_props).cloned().collect();

        let dto_simple = base_obj.name.as_deref().unwrap_or(type_name.as_str());
        let dto_simple = dto_simple.rsplit('.').next().unwrap_or(dto_simple);

        for (i, removed) in removed_props.iter().enumerate() {
            let (fix, rec) = if let Some(added) = added_props.get(i) {
                (
                    format!("@JsonProperty(\"{}\")", removed),
                    format!(
                        "Add @JsonProperty(\"{}\") to {} in {} to preserve REST contract without breaking consumers.",
                        removed, added, dto_simple
                    ),
                )
            } else {
                (
                    format!("Restore wire property '{}'", removed),
                    format!(
                        "Property '{}' was removed from {}. Add @JsonProperty or restore field to prevent breaking consumers.",
                        removed, dto_simple
                    ),
                )
            };
            fixes.push(PrescriptiveFix {
                dto: dto_simple.to_string(),
                file: file.clone(),
                suggested_fix: fix,
                recommendation: rec,
            });
        }
    }
    fixes
}

/// The resolved repository root: canonical, and inside an allowed root when one is configured.
pub fn resolve_repo_root(repo_root: &Path, allowed_roots: &[PathBuf]) -> Result<PathBuf> {
    let resolved = confine(repo_root, allowed_roots)
        .with_context(|| format!("Cannot resolve repository root {:?}", repo_root))?;
    if !resolved.is_dir() {
        bail!("Repository root {:?} is not a directory", resolved);
    }
    Ok(resolved)
}

pub fn analyze(allowed_roots: &[PathBuf], request: &ImpactRequest) -> Result<Value> {
    let repo_root = resolve_repo_root(&request.repo_root, allowed_roots)?;
    if request.mode != ImpactMode::CommitRange && request.commit_range.is_some() {
        bail!("commitRange is only accepted with mode commitRange");
    }

    // Ensure SQLite contract database and artifact caches are synchronized
    let _ = crate::contracts_db::sync_if_needed(&repo_root);

    let manifest = read_manifest(&repo_root)?;
    let backend = BackendScope::new(&repo_root, &manifest.backend_rel);
    let backend_dir = confine(&backend.disk_root, allowed_roots)
        .with_context(|| format!("Cannot resolve backend root {:?}", backend.disk_root))?;
    if !is_under_root(&backend_dir, &repo_root) {
        bail!(
            "Backend root {} is outside the repository {}",
            manifest.backend_rel,
            repo_root.display()
        );
    }
    if !backend_dir.is_dir() {
        bail!(
            "Backend root {} does not exist as a directory",
            manifest.backend_rel
        );
    }
    let frontend = manifest
        .frontend_rel
        .as_deref()
        .filter(|rel| !rel.is_empty())
        .map(|rel| BackendScope::new(&repo_root, rel));

    let db_path = repo_root
        .join(".sajimora")
        .join(crate::contracts_db::CONTRACTS_DB_NAME);
    let contract_sources: BTreeSet<String> =
        if let Ok(conn) = crate::contracts_db::open_reader(&db_path) {
            crate::contracts_db::load_backend_provenance_files(&conn).unwrap_or_default()
        } else {
            BTreeSet::new()
        };

    let roles = Roles {
        backend: backend.clone(),
        frontend,
        // The untracked-file scan runs before either revision is listed, so it
        // has to classify files from the checkout. The authoritative lane is
        // re-detected from the two listings below.
        provider: ProviderKind::detect_on_disk(&backend.disk_root),
        contract_sources,
    };

    let test_paths = resolve_test_paths(&repo_root, allowed_roots, &request.generated_tests)?;
    let sides = read_sides(&repo_root, request, &backend, &roles)?;

    // The lane is decided from the revisions being compared, not from the
    // working tree, so a commit range is classified by what it contains even
    // when the checkout has moved on.
    let listing_keys: Vec<String> = sides
        .base
        .0
        .keys()
        .chain(sides.candidate.0.keys())
        .cloned()
        .collect();
    let listing_provider = ProviderKind::detect_in_listing(&backend, listing_keys.iter());
    // Path conventions identify Next.js and NestJS, but Express/Fastify has no
    // mandatory convention. When the listing has real TS sources and no Java,
    // the checkout's content-based lane is the only evidence available; using
    // Spring here would classify every Express change as non-provider input.
    let has_java = listing_keys.iter().any(|path| path.ends_with(".java"));
    let has_ts = listing_keys.iter().any(|path| {
        path.ends_with(".ts")
            || path.ends_with(".tsx")
            || path.ends_with(".js")
            || path.ends_with(".jsx")
            || path.ends_with(".mjs")
            || path.ends_with(".cjs")
    });
    let provider_kind = if listing_provider == ProviderKind::Spring
        && !has_java
        && has_ts
        && matches!(
            roles.provider,
            ProviderKind::Express | ProviderKind::NextJs | ProviderKind::NestJs
        ) {
        roles.provider
    } else {
        listing_provider
    };
    let roles = Roles {
        provider: provider_kind,
        ..roles
    };
    let changes = diff_listings(&sides.base, &sides.candidate);

    let mut changed: BTreeSet<String> = BTreeSet::new();
    let mut changed_files = Vec::new();
    let mut role_counts: BTreeMap<&'static str, usize> = BTreeMap::new();
    for (path, change) in &changes {
        let role = roles.role(path);
        changed.insert(path.clone());
        *role_counts.entry(role.label()).or_insert(0) += 1;
        changed_files.push(json!({
            "path": path,
            "change": change.label(),
            "role": role.label(),
        }));
    }

    let provider_changed = changes.iter().any(|(path, _)| {
        matches!(
            roles.role(path),
            Role::ProviderSource | Role::ExtractorConfig
        )
    });

    let is_config_changed = changes
        .iter()
        .any(|(path, _)| roles.role(path) == Role::ExtractorConfig);

    let slice_filter: Option<BTreeSet<String>> = if !is_config_changed && provider_changed {
        if let Ok(conn) = crate::contracts_db::open_reader(&db_path) {
            let changed_provider_sources: BTreeSet<String> = changes
                .iter()
                .filter(|(path, _)| roles.role(path) == Role::ProviderSource)
                .map(|(path, _)| path.clone())
                .collect();
            if !changed_provider_sources.is_empty() {
                let ctrls = crate::contracts_db::query_dependent_controllers(
                    &conn,
                    &changed_provider_sources,
                )
                .unwrap_or_default();
                let mut all_ctrls = ctrls;
                for p in &changed_provider_sources {
                    if p.ends_with("Controller.java") || p.ends_with("Resource.java") {
                        all_ctrls.insert(p.clone());
                    }
                }
                if !all_ctrls.is_empty() {
                    let dtos =
                        crate::contracts_db::query_controller_dependencies(&conn, &all_ctrls)
                            .unwrap_or_default();
                    let mut slice = changed_provider_sources;
                    slice.extend(all_ctrls);
                    slice.extend(dtos);
                    Some(slice)
                } else {
                    None
                }
            } else {
                None
            }
        } else {
            None
        }
    } else {
        None
    };

    let extracted = if provider_changed {
        Some(extract_sides(
            &repo_root,
            &backend,
            provider_kind,
            &manifest.service_id,
            &sides,
            &roles.contract_sources,
            slice_filter.as_ref(),
        )?)
    } else {
        None
    };

    let (base_eps, cand_eps) = match &extracted {
        Some((base, candidate)) => (index_endpoints(base)?, index_endpoints(candidate)?),
        None => (BTreeMap::new(), BTreeMap::new()),
    };

    let affected = affected_endpoints(&base_eps, &cand_eps, &changed);
    let consumers = collect_consumers(
        allowed_roots,
        &repo_root,
        &affected,
        &base_eps,
        &cand_eps,
        extracted.as_ref(),
    )?;
    let tests = read_generated_tests(&repo_root, &test_paths, &affected)?;

    let mut endpoint_reasons: Vec<Value> = Vec::new();
    let mut attributed: BTreeSet<String> = BTreeSet::new();
    let mut unattributed_contracts: Vec<String> = Vec::new();
    for entry in &affected {
        for file in &entry.attributed {
            attributed.insert(file.clone());
        }
        if entry.attributed.is_empty() {
            unattributed_contracts.push(entry.key.clone());
        }
    }

    let unattributed_sources: Vec<String> = changes
        .iter()
        .filter(|(path, _)| roles.role(path) == Role::ProviderSource)
        .map(|(path, _)| path.clone())
        .filter(|path| !attributed.contains(path))
        .collect();
    if !unattributed_sources.is_empty() {
        endpoint_reasons.push(reason(
            "UNATTRIBUTED_SOURCE_CHANGE",
            "Provider source changed but no affected endpoint records it in provenance; effects outside the sealed contract shape (behaviour, wiring, superclass fields) cannot be attributed without a dependency graph.",
            json!({ "files": unattributed_sources }),
        ));
    }
    if !unattributed_contracts.is_empty() {
        endpoint_reasons.push(reason(
            "UNATTRIBUTED_CONTRACT_CHANGE",
            "The response or request shape changed through a channel the endpoint does not record as source provenance (superclass, configuration, route constant, or composed annotation).",
            json!({ "endpoints": unattributed_contracts }),
        ));
    }

    let config_changes: Vec<String> = changes
        .iter()
        .filter(|(path, _)| roles.role(path) == Role::ExtractorConfig)
        .map(|(path, _)| path.clone())
        .collect();
    if !config_changes.is_empty() {
        endpoint_reasons.push(reason(
            "EXTRACTOR_CONFIG_CHANGED",
            "Extractor configuration changed; its effect on wire names is folded into endpoint fingerprints but is not attributed to individual endpoints.",
            json!({ "files": config_changes }),
        ));
    }

    let mut unmodeled: Vec<String> = changes
        .iter()
        .filter(|(path, _)| {
            matches!(
                roles.role(path),
                Role::BuildFile | Role::UnmodeledBackendInput
            )
        })
        .map(|(path, _)| path.clone())
        .collect();
    unmodeled.sort();
    if !unmodeled.is_empty() {
        endpoint_reasons.push(reason(
            "UNMODELED_BACKEND_INPUT",
            "Backend input changed that extraction never reads (build files, sources outside the extracted provider lane, or resources); endpoints were not recomputed from it.",
            json!({ "files": unmodeled }),
        ));
    }

    let out_of_scope: Vec<String> = changes
        .iter()
        .filter(|(path, _)| roles.role(path) == Role::OutOfScopeJava)
        .map(|(path, _)| path.clone())
        .collect();
    if !out_of_scope.is_empty() {
        endpoint_reasons.push(reason(
            "OUT_OF_SCOPE_JAVA_CHANGE",
            "Java source changed outside the backend root; it is not part of this provider's extracted contract.",
            json!({ "files": out_of_scope }),
        ));
    }

    let mut extraction_incomplete = false;
    if let Some((base_env, candidate_env)) = &extracted {
        let base_bad = !base_env.completeness.complete;
        let cand_bad = !candidate_env.completeness.complete;
        extraction_incomplete = base_bad || cand_bad;
        if extraction_incomplete {
            let mut codes: BTreeSet<String> = BTreeSet::new();
            for env in [base_env, candidate_env] {
                codes.extend(env.completeness.blockers.iter().map(|b| b.code.clone()));
            }
            endpoint_reasons.push(reason(
                "EXTRACTION_BLOCKER",
                "Provider extraction reported blockers or unresolved endpoints; an endpoint may be missing from a side of this comparison.",
                json!({
                    "base": extraction_completeness(base_env),
                    "candidate": extraction_completeness(candidate_env),
                    "codes": codes.into_iter().collect::<Vec<_>>(),
                }),
            ));
        }
    }
    let endpoints_layer = layer(endpoint_reasons);

    let mut consumer_reasons: Vec<Value> = consumers.reasons.clone();
    if consumers.admitted_artifacts == 0 {
        consumer_reasons.push(reason(
            "NO_CONSUMER_CONTRACTS",
            "No sealed frontend contract artifact was admitted, so no consumer call site could be linked.",
            json!({}),
        ));
    }
    let changed_consumer_sources: Vec<String> = changes
        .iter()
        .filter(|(path, _)| roles.role(path) == Role::ConsumerSource)
        .map(|(path, _)| path.clone())
        .collect();
    if !changed_consumer_sources.is_empty() {
        consumer_reasons.push(reason(
            "CONSUMER_SOURCES_CHANGED",
            "Frontend source files changed, but consumer call sites come from sealed artifacts extracted earlier; they are not recomputed from these files.",
            json!({ "files": changed_consumer_sources }),
        ));
    }
    if !consumers.unlinkable.is_empty() {
        consumer_reasons.push(reason(
            "UNLINKABLE_CONSUMER_CONTRACTS",
            "A same-method client route could not be linked to any affected endpoint (absolute URL outside declared base URLs, or an unresolved interpolation placeholder).",
            json!({ "clients": consumers.unlinkable }),
        ));
    }
    if !consumers.traversal_incomplete.is_empty() {
        consumer_reasons.push(reason(
            "CONSUMER_TRAVERSAL_INCOMPLETE",
            "The sealed artifact marks consumer traversal as incomplete for this client, so its recorded call sites may be partial.",
            json!({ "clients": consumers.traversal_incomplete }),
        ));
    }
    if !consumers.target_mismatches.is_empty() {
        consumer_reasons.push(reason(
            "CONSUMER_TARGET_MISMATCH",
            "A same-method client targets a different service id or API version than the provider artifact records; it was left unlinked rather than guessed.",
            json!({ "clients": consumers.target_mismatches }),
        ));
    }
    let consumers_layer = layer(consumer_reasons);

    let mut test_reasons = vec![reason(
        "GENERATED_TEST_PROVENANCE_UNRECORDED",
        "Synthesis output records no source artifact digest or revision, so a marker proves a route was synthesized against some artifact, not against this candidate revision.",
        json!({}),
    )];
    if test_paths.is_empty() {
        test_reasons.push(reason(
            "NO_GENERATED_TESTS_PROVIDED",
            "No generated test files were supplied, so generated-test coverage is unknown, not absent.",
            json!({}),
        ));
    }
    if !tests.not_generated.is_empty() {
        test_reasons.push(reason(
            "NOT_A_GENERATED_TEST",
            "A supplied file does not carry the Sajimora synthesis header.",
            json!({ "files": tests.not_generated }),
        ));
    }
    let tests_layer = layer(test_reasons);

    let mut incomplete_layers = Vec::new();
    for (name, block) in [
        ("consumers", &consumers_layer),
        ("endpoints", &endpoints_layer),
        ("generatedTests", &tests_layer),
    ] {
        if block.get("complete").and_then(Value::as_bool) == Some(false) {
            incomplete_layers.push(name);
        }
    }

    let (base_pool, cand_pool) = match &extracted {
        Some((b, c)) => match (&b.payload, &c.payload) {
            (ArtifactPayload::Backend(bp), ArtifactPayload::Backend(cp)) => {
                (bp.type_pool.as_ref(), cp.type_pool.as_ref())
            }
            _ => (None, None),
        },
        None => (None, None),
    };
    let prescriptive_fixes = detect_prescriptive_fixes(base_pool, cand_pool, &changed);

    let summary = json!({
        "changedFiles": changed.len(),
        "affectedEndpoints": affected.len(),
        "addedEndpoints": affected.iter().filter(|e| e.change == EndpointChange::Added).count(),
        "removedEndpoints": affected.iter().filter(|e| e.change == EndpointChange::Removed).count(),
        "contractChangedEndpoints": affected.iter().filter(|e| e.change == EndpointChange::ContractChanged).count(),
        "evidenceChangedEndpoints": affected.iter().filter(|e| e.change == EndpointChange::EvidenceChanged).count(),
        "consumerLinks": consumers.linked,
        "generatedTestMarkers": tests.marker_count,
        "incompleteLayers": incomplete_layers,
        "exactTestSelection": false,
        "suggestedFixesCount": prescriptive_fixes.len(),
        "roleCounts": Value::Object(role_counts.iter().map(|(k, v)| (k.to_string(), json!(v))).collect()),
    });

    let endpoints_json: Vec<Value> = affected
        .iter()
        .map(|entry| {
            let mut endpoint_reasons: Vec<&str> = Vec::new();
            if unattributed_contracts.iter().any(|key| key == &entry.key) {
                endpoint_reasons.push("CONTRACT_CHANGE_WITHOUT_PROVENANCE");
            }
            let fix = prescriptive_fixes
                .iter()
                .find(|f| entry.attributed.contains(&f.file));
            let mut ep_json = json!({
                "method": entry.method,
                "path": entry.route,
                "change": entry.change.label(),
                "definedAt": match &entry.defined_at {
                    Some((file, line)) => json!({ "file": file, "line": line }),
                    None => Value::Null,
                },
                "attributedFiles": entry.attributed.iter().collect::<Vec<_>>(),
                "consumers": consumers.by_endpoint.get(&entry.key).cloned().unwrap_or_default(),
                "generatedTests": tests.by_endpoint.get(&entry.key).cloned().unwrap_or_default(),
                "reasonCodes": endpoint_reasons,
            });
            if let Some(f) = fix {
                ep_json["suggestedFix"] = json!(f.suggested_fix);
                ep_json["recommendation"] = json!(f.recommendation);
            }
            ep_json
        })
        .collect();

    let provider = json!({
        "serviceId": manifest.service_id,
        "backendRoot": display_root(&manifest.backend_rel),
        "frameworkProfile": provider_kind.framework_profile(),
        "extraction": if extracted.is_some() { "EXTRACTED" } else { "NOT_RUN_NO_PROVIDER_INPUT_CHANGED" },
        "endpointCount": {
            "base": if extracted.is_some() { json!(base_eps.len()) } else { Value::Null },
            "candidate": if extracted.is_some() { json!(cand_eps.len()) } else { Value::Null },
        },
        "completeness": match &extracted {
            Some((base_env, candidate_env)) => json!({
                "base": extraction_completeness(base_env),
                "candidate": extraction_completeness(candidate_env),
            }),
            None => Value::Null,
        },
        "clean": if extracted.is_some() { json!(!extraction_incomplete) } else { Value::Null },
    });

    let reason_codes = reason_index(
        &[
            ("endpoints", &endpoints_layer),
            ("consumers", &consumers_layer),
            ("generatedTests", &tests_layer),
        ],
        extracted.as_ref(),
    );

    Ok(json!({
        "schemaVersion": SCHEMA_VERSION,
        "advisory": true,
        "notice": NOTICE,
        "revision": {
            "mode": request.mode.label(),
            "base": { "kind": sides.base_id.0, "id": sides.base_id.1 },
            "candidate": { "kind": sides.candidate_id.0, "id": sides.candidate_id.1 },
            "untrackedFiles": {
                "scope": if sides.untracked_scanned { "backendRoot" } else { "notScanned" },
                "count": sides.untracked,
            },
        },
        "provider": provider,
        "summary": summary,
        "reasonCodes": reason_codes,
        "completeness": {
            "endpoints": endpoints_layer,
            "consumers": consumers_layer,
            "generatedTests": tests_layer,
        },
        "changedFiles": changed_files,
        "endpoints": endpoints_json,
        "suggestedFixes": prescriptive_fixes,
        "consumerArtifacts": consumers.artifacts,
        "rejectedConsumerArtifacts": consumers.rejected,
        "nonConsumerArtifacts": consumers.non_consumer,
        "generatedTestFiles": tests.files,
    }))
}

pub fn render_report(report: &Value) -> String {
    let mut text = serde_json::to_string_pretty(report).unwrap_or_else(|_| "{}".to_string());
    text.push('\n');
    text
}

pub fn summary_line(report: &Value) -> String {
    let summary = &report["summary"];
    let count = |key: &str| summary.get(key).and_then(Value::as_u64).unwrap_or(0);
    let layers = summary
        .get("incompleteLayers")
        .and_then(Value::as_array)
        .map(|items| {
            items
                .iter()
                .filter_map(Value::as_str)
                .collect::<Vec<_>>()
                .join(",")
        })
        .unwrap_or_else(|| "none".to_string());
    let mut text = format!(
        "endpoint-impact: {} changed file(s), {} affected endpoint(s) (added {}, removed {}, contract-changed {}, evidence-only {}), {} consumer link(s), {} generated-test marker(s); incomplete layers: {} (advisory, no test selection)",
        count("changedFiles"),
        count("affectedEndpoints"),
        count("addedEndpoints"),
        count("removedEndpoints"),
        count("contractChangedEndpoints"),
        count("evidenceChangedEndpoints"),
        count("consumerLinks"),
        count("generatedTestMarkers"),
        layers
    );
    if let Some(fixes) = report.get("suggestedFixes").and_then(Value::as_array) {
        if let Some(first) = fixes.first() {
            if let Some(rec) = first.get("recommendation").and_then(Value::as_str) {
                text.push_str(&format!("\n💡 Prescriptive Fix: {rec}"));
            }
        }
    }
    text
}

/// Validate a report destination. The default lives beside the other Sajimora
/// artifacts; the legacy `impact-report.json` name is refused outright.
pub fn resolve_output_path(
    repo_root: &Path,
    requested: Option<&Path>,
    allowed_roots: &[PathBuf],
) -> Result<PathBuf> {
    let candidate = match requested {
        Some(path) => {
            if path.components().any(|c| matches!(c, Component::ParentDir)) {
                bail!("Output path {:?} must not contain '..'", path);
            }
            if path.is_absolute() {
                path.to_path_buf()
            } else {
                repo_root.join(path)
            }
        }
        None => repo_root.join(DEFAULT_OUTPUT),
    };
    let name = candidate
        .file_name()
        .and_then(|n| n.to_str())
        .context("Output path has no file name")?;
    if name.eq_ignore_ascii_case(RESERVED_OUTPUT_FILE) {
        bail!("{name} is reserved for the legacy impact report; choose another output name");
    }
    if !name.to_ascii_lowercase().ends_with(".json") {
        bail!("Output path {name:?} must end in .json");
    }
    let parent = candidate
        .parent()
        .context("Output path has no parent directory")?;
    if !parent.is_dir() {
        bail!("Output directory {:?} does not exist", parent);
    }
    let parent = confine(parent, allowed_roots)?;
    let name = candidate
        .file_name()
        .context("Output path has no file name")?;
    let resolved = parent.join(name);
    if resolved.exists() {
        let metadata = fs::symlink_metadata(&resolved)?;
        if !metadata.is_file() {
            bail!(
                "Output path {:?} is not a regular file; refusing to overwrite",
                resolved
            );
        }
        let bytes = read_bounded(&resolved, DEFAULT_MAX_ARTIFACT_BYTES)
            .with_context(|| format!("Cannot read existing output {:?}", resolved))?;
        let existing: Value = serde_json::from_slice(&bytes).with_context(|| {
            format!(
                "Existing file {:?} is not a Sajimora endpoint-impact report; refusing to overwrite",
                resolved
            )
        })?;
        if existing.get("schemaVersion").and_then(Value::as_str) != Some(SCHEMA_VERSION) {
            bail!(
                "Existing file {:?} is not a {} report; refusing to overwrite",
                resolved,
                SCHEMA_VERSION
            );
        }
    }
    Ok(resolved)
}

pub fn write_report(path: &Path, text: &str) -> Result<()> {
    if let Some(parent) = path.parent() {
        if !parent.is_dir() {
            bail!("Output directory {:?} does not exist", parent);
        }
    }
    fs::write(path, text).with_context(|| format!("Cannot write report to {:?}", path))?;
    Ok(())
}

