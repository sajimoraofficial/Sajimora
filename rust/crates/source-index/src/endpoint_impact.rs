struct SideEndpoint<'a> {
    contracts: Vec<&'a EndpointContract>,
    fingerprint: String,
    evidence: BTreeSet<String>,
    defined_at: Option<(String, u32)>,
}

fn endpoint_key(endpoint: &EndpointContract) -> String {
    format!(
        "{} {}",
        endpoint.identity.http_method.to_uppercase(),
        endpoint.identity.normalized_route.raw_path
    )
}

fn index_endpoints<'a>(
    envelope: &'a ContractArtifactEnvelope,
) -> Result<BTreeMap<String, SideEndpoint<'a>>> {
    let payload = match &envelope.payload {
        ArtifactPayload::Backend(payload) => payload,
        ArtifactPayload::Frontend(_) => bail!("Provider extraction produced a frontend payload"),
    };
    let mut grouped: BTreeMap<String, Vec<&'a EndpointContract>> = BTreeMap::new();
    for endpoint in &payload.endpoints {
        grouped
            .entry(endpoint_key(endpoint))
            .or_default()
            .push(endpoint);
    }
    let mut indexed = BTreeMap::new();
    for (key, contracts) in grouped {
        let (fingerprint, evidence) =
            fingerprint_contracts(&contracts, payload.type_pool.as_ref())?;
        let mut defined_at: Option<(String, u32)> = None;
        for contract in &contracts {
            let candidate = (contract.provenance.file.clone(), contract.provenance.line);
            defined_at = Some(match defined_at {
                Some(current) if current <= candidate => current,
                _ => candidate,
            });
        }
        indexed.insert(
            key,
            SideEndpoint {
                contracts,
                fingerprint,
                evidence,
                defined_at,
            },
        );
    }
    Ok(indexed)
}

fn fingerprint_contracts(
    contracts: &[&EndpointContract],
    pool: Option<&BTreeMap<String, WireType>>,
) -> Result<(String, BTreeSet<String>)> {
    let mut parts = Vec::new();
    let mut files: BTreeSet<String> = BTreeSet::new();
    let mut pending: Vec<String> = Vec::new();
    for contract in contracts {
        let value = serde_json::to_value(contract)?;
        parts.push(contract_core::canonical::canonical_json(&strip_provenance(
            &value,
            &mut files,
            &mut pending,
        )));
    }
    let mut seen: BTreeSet<String> = BTreeSet::new();
    while let Some(name) = pending.pop() {
        if !seen.insert(name.clone()) {
            continue;
        }
        match pool.and_then(|pool| pool.get(&name)) {
            Some(wire_type) => {
                let value = serde_json::to_value(wire_type)?;
                parts.push(format!(
                    "ref:{name}={}",
                    contract_core::canonical::canonical_json(&strip_provenance(
                        &value,
                        &mut files,
                        &mut pending,
                    ))
                ));
            }
            None => parts.push(format!("ref:{name}=UNRESOLVED")),
        }
    }
    parts.sort();
    let mut hasher = Sha256::new();
    for part in &parts {
        hasher.update(part.as_bytes());
        hasher.update(b"\n");
    }
    let evidence = files.into_iter().collect::<BTreeSet<_>>();
    Ok((hex::encode(hasher.finalize())[..32].to_string(), evidence))
}

fn strip_provenance(value: &Value, files: &mut BTreeSet<String>, refs: &mut Vec<String>) -> Value {
    match value {
        Value::Object(map) => {
            let mut out = Map::new();
            for (key, child) in map {
                if key == "provenance" {
                    if let Some(file) = child.get("file").and_then(Value::as_str) {
                        files.insert(file.to_string());
                    }
                    continue;
                }
                if key == "ref" {
                    if let Some(name) = child.as_str() {
                        refs.push(name.to_string());
                    }
                }
                out.insert(key.clone(), strip_provenance(child, files, refs));
            }
            Value::Object(out)
        }
        Value::Array(items) => Value::Array(
            items
                .iter()
                .map(|item| strip_provenance(item, files, refs))
                .collect(),
        ),
        other => other.clone(),
    }
}

struct Affected {
    key: String,
    method: String,
    route: String,
    change: EndpointChange,
    attributed: BTreeSet<String>,
    defined_at: Option<(String, u32)>,
}

fn affected_endpoints(
    base: &BTreeMap<String, SideEndpoint<'_>>,
    candidate: &BTreeMap<String, SideEndpoint<'_>>,
    changed: &BTreeSet<String>,
) -> Vec<Affected> {
    let mut keys: BTreeSet<&String> = base.keys().collect();
    keys.extend(candidate.keys());
    let mut affected = Vec::new();
    for key in keys {
        let (method, route) = match key.split_once(' ') {
            Some((method, route)) => (method.to_string(), route.to_string()),
            None => continue,
        };
        let (change, evidence, defined_at) = match (base.get(key), candidate.get(key)) {
            (None, Some(candidate_side)) => (
                EndpointChange::Added,
                candidate_side.evidence.clone(),
                candidate_side.defined_at.clone(),
            ),
            (Some(base_side), None) => (
                EndpointChange::Removed,
                base_side.evidence.clone(),
                base_side.defined_at.clone(),
            ),
            (Some(base_side), Some(candidate_side)) => {
                let mut evidence = base_side.evidence.clone();
                evidence.extend(candidate_side.evidence.iter().cloned());
                let change = if base_side.fingerprint != candidate_side.fingerprint {
                    EndpointChange::ContractChanged
                } else if evidence.iter().any(|file| changed.contains(file)) {
                    EndpointChange::EvidenceChanged
                } else {
                    continue;
                };
                (
                    change,
                    evidence,
                    candidate_side
                        .defined_at
                        .clone()
                        .or_else(|| base_side.defined_at.clone()),
                )
            }
            (None, None) => continue,
        };
        let attributed: BTreeSet<String> = evidence
            .into_iter()
            .filter(|file| changed.contains(file))
            .collect();
        affected.push(Affected {
            key: key.clone(),
            method,
            route,
            change,
            attributed,
            defined_at,
        });
    }
    affected
}

