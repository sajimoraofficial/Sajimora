#[derive(Debug, Clone)]
struct FileEntry {
    oid: String,
    size: Option<u64>,
}

#[derive(Debug, Default)]
struct Listing(BTreeMap<String, FileEntry>);

struct Sides {
    base: Listing,
    candidate: Listing,
    base_id: (&'static str, String),
    candidate_id: (&'static str, String),
    candidate_source: ListingSource,
    untracked: usize,
    untracked_scanned: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Change {
    Added,
    Modified,
    Deleted,
}

impl Change {
    fn label(self) -> &'static str {
        match self {
            Change::Added => "ADDED",
            Change::Modified => "MODIFIED",
            Change::Deleted => "DELETED",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum EndpointChange {
    Added,
    Removed,
    ContractChanged,
    EvidenceChanged,
}

impl EndpointChange {
    fn label(self) -> &'static str {
        match self {
            EndpointChange::Added => "ADDED",
            EndpointChange::Removed => "REMOVED",
            EndpointChange::ContractChanged => "CONTRACT_CHANGED",
            EndpointChange::EvidenceChanged => "EVIDENCE_CHANGED",
        }
    }
}

fn read_sides(
    repo: &Path,
    request: &ImpactRequest,
    backend: &BackendScope,
    roles: &Roles,
) -> Result<Sides> {
    match request.mode {
        ImpactMode::CommitRange => {
            let range = request
                .commit_range
                .as_deref()
                .context("commitRange mode requires --commit-range <a>..<b>")?;
            let (base_rev, candidate_rev) = split_range(range)?;
            let base_sha = revision::resolve_commit(repo, &base_rev)?;
            let candidate_sha = revision::resolve_commit(repo, &candidate_rev)?;
            Ok(Sides {
                base: tree_listing(repo, &base_sha)?,
                candidate: tree_listing(repo, &candidate_sha)?,
                base_id: ("GIT_TREE", base_sha),
                candidate_id: ("GIT_TREE", candidate_sha),
                candidate_source: ListingSource::GitObjects,
                untracked: 0,
                untracked_scanned: false,
            })
        }
        ImpactMode::Staged => {
            let head = revision::head_commit(repo)?;
            let base = tree_listing(repo, &head)?;
            let candidate = index_listing(revision::index_entries(repo)?);
            let token = listing_token(&candidate);
            Ok(Sides {
                base,
                candidate,
                base_id: ("GIT_TREE", head),
                candidate_id: ("GIT_INDEX", format!("staged:{token}")),
                candidate_source: ListingSource::GitObjects,
                untracked: 0,
                untracked_scanned: false,
            })
        }
        ImpactMode::WorkingTree => {
            let head = revision::head_commit(repo)?;
            let index = revision::index_entries(repo)?;
            let base = tree_listing(repo, &head)?;
            let (candidate, untracked) = working_tree_listing(repo, backend, &index, &base, roles)?;
            let token = listing_token(&candidate);
            Ok(Sides {
                base,
                candidate,
                base_id: ("GIT_TREE", head),
                candidate_id: ("WORKING_TREE", format!("worktree:{token}")),
                candidate_source: ListingSource::WorkingTree,
                untracked,
                untracked_scanned: true,
            })
        }
    }
}

fn split_range(range: &str) -> Result<(String, String)> {
    if range.contains("...") {
        bail!("Symmetric ranges are not supported; use <base>..<candidate>");
    }
    let (base, candidate) = range
        .split_once("..")
        .context("commit range must be <base>..<candidate>")?;
    if base.is_empty() || candidate.is_empty() {
        bail!("commit range must name both sides: <base>..<candidate>");
    }
    Ok((base.to_string(), candidate.to_string()))
}

fn tree_listing(repo: &Path, commit: &str) -> Result<Listing> {
    let mut listing = Listing::default();
    for entry in revision::tree_entries(repo, commit)? {
        if entry.mode != "100644" && entry.mode != "100755" {
            continue;
        }
        if entry.path.starts_with(".sajimora/") {
            continue;
        }
        listing.0.insert(
            entry.path,
            FileEntry {
                oid: entry.oid.to_ascii_lowercase(),
                size: Some(entry.bytes),
            },
        );
    }
    Ok(listing)
}

fn index_listing(entries: Vec<(String, String)>) -> Listing {
    let mut listing = Listing::default();
    for (path, oid) in entries {
        if path.starts_with(".sajimora/") {
            continue;
        }
        listing.0.insert(
            path,
            FileEntry {
                oid: oid.to_ascii_lowercase(),
                size: None,
            },
        );
    }
    listing
}

fn working_tree_listing(
    repo: &Path,
    backend: &BackendScope,
    index: &[(String, String)],
    base: &Listing,
    roles: &Roles,
) -> Result<(Listing, usize)> {
    let mut known: HashMap<&str, &str> = HashMap::new();
    for (path, entry) in &base.0 {
        known.insert(path.as_str(), entry.oid.as_str());
    }
    for (path, oid) in index {
        known.insert(path.as_str(), oid.as_str());
    }

    let mut tracked: BTreeSet<String> = base.0.keys().cloned().collect();
    tracked.extend(index.iter().map(|(path, _)| path.clone()));

    // Zero-trust stat cache: load from .sajimora/contracts.db to avoid reading/hashing untouched files
    let db_path = repo
        .join(".sajimora")
        .join(crate::contracts_db::CONTRACTS_DB_NAME);
    let mut db_conn = if db_path.exists() {
        crate::contracts_db::open_writer(&db_path).ok()
    } else {
        None
    };
    let stat_cache = if let Some(ref conn) = db_conn {
        crate::contracts_db::load_stat_cache(conn).unwrap_or_default()
    } else {
        HashMap::new()
    };

    use rayon::prelude::*;
    let checked_files: Vec<(String, PathBuf, u64, u128)> = tracked
        .par_iter()
        .filter(|p| !p.starts_with(".sajimora/"))
        .filter_map(|path| {
            let full = repo.join(path);
            let metadata = fs::symlink_metadata(&full).ok()?;
            if !metadata.is_file() {
                return None;
            }
            let size = metadata.len();
            let mtime = metadata
                .modified()
                .ok()
                .and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok())
                .map(|d| d.as_nanos())
                .unwrap_or(0);
            Some((path.clone(), full, size, mtime))
        })
        .collect();

    let mut mutations_to_cache: Vec<(String, u64, u128, String)> = Vec::new();
    let mut listing = Listing::default();
    for (path, full, size, mtime) in checked_files {
        let oid =
            if let Some((cached_size, cached_mtime, cached_oid)) = stat_cache.get(path.as_str()) {
                if *cached_size == size && *cached_mtime == mtime {
                    cached_oid.clone()
                } else {
                    let computed = worktree_oid(&full, size, known.get(path.as_str()).copied())?;
                    mutations_to_cache.push((path.clone(), size, mtime, computed.clone()));
                    computed
                }
            } else {
                let computed = worktree_oid(&full, size, known.get(path.as_str()).copied())?;
                mutations_to_cache.push((path.clone(), size, mtime, computed.clone()));
                computed
            };

        listing.0.insert(
            path,
            FileEntry {
                oid,
                size: Some(size),
            },
        );
    }

    // Persist any updated stat cache entries atomically
    if let Some(ref mut conn) = db_conn {
        if !mutations_to_cache.is_empty() {
            let _ = crate::contracts_db::save_stat_cache_entries(conn, &mutations_to_cache);
        }
    }

    let (untracked_files, _) = untracked_inputs(repo, backend, &tracked, roles)?;
    let count = untracked_files.len();
    for (path, oid, size) in untracked_files {
        listing.0.insert(path, FileEntry { oid, size });
    }
    Ok((listing, count))
}

fn untracked_inputs(
    repo: &Path,
    backend: &BackendScope,
    tracked: &BTreeSet<String>,
    roles: &Roles,
) -> Result<(Vec<(String, String, Option<u64>)>, usize)> {
    let mut found = Vec::new();
    let mut visited_dirs = 0usize;
    let mut stack = vec![backend.disk_root.clone()];
    while let Some(dir) = stack.pop() {
        let entries = match fs::read_dir(&dir) {
            Ok(entries) => entries,
            Err(_) => continue,
        };
        let mut paths: Vec<PathBuf> = entries.flatten().map(|entry| entry.path()).collect();
        paths.sort();
        for path in paths {
            let Ok(metadata) = fs::symlink_metadata(&path) else {
                continue;
            };
            if metadata.file_type().is_symlink() {
                continue;
            }
            if metadata.is_dir() {
                if is_pruned_dir(&path) || path.join(".git").exists() {
                    continue;
                }
                visited_dirs += 1;
                if visited_dirs > MAX_WALK_DIRS {
                    bail!("Untracked scan exceeded {MAX_WALK_DIRS} directories under the backend root");
                }
                stack.push(path);
                continue;
            }
            if !metadata.is_file() {
                continue;
            }
            let Ok(rel) = path.strip_prefix(repo) else {
                continue;
            };
            let repo_path = rel.to_string_lossy().replace('\\', "/");
            if repo_path.starts_with(".sajimora/") || tracked.contains(&repo_path) {
                continue;
            }
            if !matches!(
                roles.role(&repo_path),
                Role::ProviderSource | Role::ExtractorConfig
            ) {
                continue;
            }
            if found.len() >= MAX_BLOBS {
                bail!("Untracked provider inputs exceed {MAX_BLOBS} files");
            }
            let oid = worktree_oid(&path, metadata.len(), None)?;
            found.push((repo_path, oid, Some(metadata.len())));
        }
    }

    // Lombok also reads a configuration at the repository root, which lies
    // outside a nested backend root and so is not reached by the walk.
    if !backend.prefix.is_empty() && !tracked.contains("lombok.config") {
        let root = repo.join("lombok.config");
        if fs::symlink_metadata(&root).is_ok_and(|metadata| metadata.is_file()) {
            let size = fs::metadata(&root)?.len();
            let oid = worktree_oid(&root, size, None)?;
            found.push(("lombok.config".to_string(), oid, Some(size)));
        }
    }
    found.sort_by(|a, b| a.0.cmp(&b.0));
    Ok((found, visited_dirs))
}

/// The blob id of a working-tree file. `expected` is the id HEAD or the index
/// records: content that normalizes to it carries CRLF that the checkin
/// conversion strips, and taking the raw id would report an unchanged file as
/// modified.
fn worktree_oid(path: &Path, size: u64, expected: Option<&str>) -> Result<String> {
    let (raw, crlf_pairs) = hash_file(path, size, false)?;
    if Some(raw.as_str()) == expected || crlf_pairs == 0 {
        return Ok(raw);
    }
    let (normalized, _) = hash_file(path, size, true)?;
    if Some(normalized.as_str()) == expected {
        return Ok(normalized);
    }
    Ok(raw)
}

fn hash_file(path: &Path, size: u64, normalize_crlf: bool) -> Result<(String, u64)> {
    use std::io::Read;
    let mut file = fs::File::open(path).with_context(|| format!("Cannot read {:?}", path))?;
    if !file.metadata()?.is_file() {
        bail!("{:?} is not a regular file", path);
    }
    if size > MAX_JAVA_BLOB_BYTES {
        return hash_stream(&mut file, size, normalize_crlf);
    }
    let mut body = Vec::with_capacity(size as usize);
    file.read_to_end(&mut body)?;
    if body.len() as u64 != size {
        bail!("{:?} changed while it was being analyzed", path);
    }
    let pairs = count_crlf(&body) as u64;
    if normalize_crlf && pairs > 0 {
        if let Some(normalized) = revision::crlf_to_lf(&body) {
            return Ok((revision::blob_oid(&normalized), pairs));
        }
    }
    Ok((revision::blob_oid(&body), pairs))
}

fn hash_stream(
    reader: &mut impl std::io::Read,
    size: u64,
    normalize_crlf: bool,
) -> Result<(String, u64)> {
    use sha1::Digest as _;
    let mut hasher = sha1::Sha1::new();
    hasher.update(format!("blob {size}\0").as_bytes());
    let mut buffer = vec![0u8; HASH_CHUNK];
    let mut total = 0u64;
    let mut pairs = 0u64;
    let mut pending_cr = false;
    loop {
        let read = reader.read(&mut buffer)?;
        if read == 0 {
            break;
        }
        total += read as u64;
        let chunk = &buffer[..read];
        if normalize_crlf {
            feed_normalized(&mut hasher, chunk, &mut pending_cr, &mut pairs);
        } else {
            hasher.update(chunk);
        }
    }
    if pending_cr {
        hasher.update(b"\r");
    }
    if total != size {
        bail!("Working-tree file changed while it was being analyzed");
    }
    Ok((hex::encode(hasher.finalize()), pairs))
}

fn feed_normalized(hasher: &mut sha1::Sha1, bytes: &[u8], pending_cr: &mut bool, pairs: &mut u64) {
    use sha1::Digest as _;
    let mut index = 0usize;
    if *pending_cr {
        if bytes.first() == Some(&b'\n') {
            hasher.update(b"\n");
            *pairs += 1;
            index = 1;
        } else {
            hasher.update(b"\r");
        }
        *pending_cr = false;
    }
    while index < bytes.len() {
        if bytes[index] == b'\r' {
            if index + 1 < bytes.len() {
                if bytes[index + 1] == b'\n' {
                    hasher.update(b"\n");
                    *pairs += 1;
                    index += 2;
                } else {
                    hasher.update(b"\r");
                    index += 1;
                }
            } else {
                *pending_cr = true;
                index += 1;
            }
            continue;
        }
        let start = index;
        while index < bytes.len() && bytes[index] != b'\r' {
            index += 1;
        }
        hasher.update(&bytes[start..index]);
    }
}

fn count_crlf(bytes: &[u8]) -> usize {
    bytes.windows(2).filter(|pair| pair == b"\r\n").count()
}

fn listing_token(listing: &Listing) -> String {
    let mut hasher = Sha256::new();
    for (path, entry) in &listing.0 {
        hasher.update(path.as_bytes());
        hasher.update(b"\0");
        hasher.update(entry.oid.as_bytes());
        hasher.update(b"\n");
    }
    hex::encode(hasher.finalize())[..16].to_string()
}

fn diff_listings(base: &Listing, candidate: &Listing) -> Vec<(String, Change)> {
    let mut changes = Vec::new();
    for (path, entry) in &candidate.0 {
        match base.0.get(path) {
            None => changes.push((path.clone(), Change::Added)),
            Some(base_entry) if base_entry.oid != entry.oid => {
                changes.push((path.clone(), Change::Modified));
            }
            Some(_) => {}
        }
    }
    for path in base.0.keys() {
        if !candidate.0.contains_key(path) {
            changes.push((path.clone(), Change::Deleted));
        }
    }
    changes.sort();
    changes
}

