struct Manifest {
    backend_rel: String,
    frontend_rel: Option<String>,
    service_id: String,
}

fn read_manifest(repo_root: &Path) -> Result<Manifest> {
    let path = repo_root.join(MANIFEST_PATH);
    let bytes = read_bounded(&path, MAX_MANIFEST_BYTES).with_context(|| {
        format!(
            "Cannot read {}; run `sajimora init` before analyzing endpoint impact",
            MANIFEST_PATH
        )
    })?;
    let value: Value =
        serde_json::from_slice(&bytes).with_context(|| format!("Invalid {MANIFEST_PATH}"))?;
    let roots = value
        .get("roots")
        .and_then(Value::as_object)
        .context("init manifest has no roots object")?;
    let backend_rel = roots
        .get("backend_root")
        .and_then(Value::as_str)
        .map(clean_relative)
        .transpose()?
        .unwrap_or_default();
    let frontend_rel = roots
        .get("frontend_root")
        .and_then(Value::as_str)
        .and_then(|raw| clean_relative(raw).ok());
    let service_id = roots
        .get("service_id")
        .and_then(Value::as_str)
        .filter(|value| !value.is_empty())
        .unwrap_or("provider")
        .to_string();
    Ok(Manifest {
        backend_rel,
        frontend_rel,
        service_id,
    })
}

fn clean_relative(raw: &str) -> Result<String> {
    let normalized = raw.trim().replace('\\', "/");
    if normalized.starts_with('/') || Path::new(&normalized).is_absolute() {
        bail!("Path {raw:?} is not repository-relative");
    }
    let trimmed = normalized.trim_matches('/');
    if trimmed.is_empty() {
        return Ok(String::new());
    }
    let mut parts = Vec::new();
    for part in trimmed.split('/') {
        match part {
            "" | "." => continue,
            ".." => bail!("Path {raw:?} escapes the repository"),
            _ => parts.push(part),
        }
    }
    Ok(parts.join("/"))
}

fn display_root(rel: &str) -> String {
    if rel.is_empty() {
        ".".to_string()
    } else {
        rel.to_string()
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Role {
    ProviderSource,
    ExcludedSource,
    OutOfScopeJava,
    ExtractorConfig,
    BuildFile,
    ConsumerSource,
    UnmodeledBackendInput,
    NotAnalyzed,
}

impl Role {
    fn label(self) -> &'static str {
        match self {
            Role::ProviderSource => "PROVIDER_SOURCE",
            Role::ExcludedSource => "EXCLUDED_SOURCE",
            Role::OutOfScopeJava => "OUT_OF_SCOPE_JAVA",
            Role::ExtractorConfig => "EXTRACTOR_CONFIG",
            Role::BuildFile => "BUILD_FILE",
            Role::ConsumerSource => "CONSUMER_SOURCE",
            Role::UnmodeledBackendInput => "UNMODELED_BACKEND_INPUT",
            Role::NotAnalyzed => "NOT_ANALYZED",
        }
    }
}

struct Roles {
    backend: BackendScope,
    frontend: Option<BackendScope>,
    provider: ProviderKind,
    contract_sources: BTreeSet<String>,
}

impl Roles {
    fn role(&self, repo_path: &str) -> Role {
        let scoped = self.backend.within(repo_path);
        if repo_path.ends_with(".java") {
            return match scoped {
                // A Java file inside a TypeScript provider module is backend
                // input neither lane reads; calling it provider source would
                // suggest the artifact models it.
                Some(_)
                    if matches!(
                        self.provider,
                        ProviderKind::NestJs | ProviderKind::NextJs | ProviderKind::Express
                    ) =>
                {
                    Role::UnmodeledBackendInput
                }
                Some(scoped) if !is_excluded_source_path(&scoped) => Role::ProviderSource,
                Some(_) => Role::ExcludedSource,
                None => {
                    if self.contract_sources.contains(repo_path)
                        && !is_excluded_source_path(repo_path)
                    {
                        Role::ProviderSource
                    } else {
                        Role::OutOfScopeJava
                    }
                }
            };
        }
        if matches!(
            self.provider,
            ProviderKind::NestJs | ProviderKind::NextJs | ProviderKind::Express
        ) {
            if let Some(scoped) = scoped.as_deref() {
                let is_provider = match self.provider {
                    ProviderKind::NestJs => is_provider_ts_file(scoped),
                    ProviderKind::NextJs => crate::nextjs_routes::is_nextjs_route_file(scoped),
                    ProviderKind::Express => crate::express_routes::is_express_source_file(scoped),
                    _ => false,
                };
                if is_provider {
                    return Role::ProviderSource;
                }
                if scoped.ends_with(".ts")
                    || scoped.ends_with(".tsx")
                    || scoped.ends_with(".js")
                    || scoped.ends_with(".jsx")
                    || scoped.ends_with(".mjs")
                    || scoped.ends_with(".cjs")
                {
                    // Spec/test/e2e files and anything under a dependency or
                    // build directory: deliberately outside the extractor.
                    return Role::ExcludedSource;
                }
            }
        }
        if matches!(self.provider, ProviderKind::Spring | ProviderKind::JaxRs) {
            if let Some(scoped) = scoped.as_deref() {
                if is_extractor_config(scoped, repo_path) {
                    return Role::ExtractorConfig;
                }
                if scoped == "lombok.config" {
                    return Role::UnmodeledBackendInput;
                }
            } else if repo_path == "lombok.config" {
                return Role::ExtractorConfig;
            }
        }
        if is_build_file(repo_path) {
            return Role::BuildFile;
        }
        if is_consumer_source(repo_path, self.frontend.as_ref()) {
            return Role::ConsumerSource;
        }
        if let Some(scoped) = scoped.as_deref() {
            if is_other_jvm_source(scoped) {
                return Role::UnmodeledBackendInput;
            }
            if scoped.starts_with("src/main/") && !is_excluded_source_path(scoped) {
                return Role::UnmodeledBackendInput;
            }
        }
        Role::NotAnalyzed
    }
}

fn is_extractor_config(scoped: &str, repo_path: &str) -> bool {
    config_tails().iter().any(|tail| *tail == scoped)
        || is_profile_config_path(scoped)
        || scoped == "lombok.config"
        || repo_path == "lombok.config"
}

fn is_build_file(repo_path: &str) -> bool {
    if repo_path.split('/').any(|part| {
        matches!(
            part,
            "node_modules" | ".git" | ".gradle" | "target" | "build" | "out"
        )
    }) {
        return false;
    }
    let name = repo_path.rsplit('/').next().unwrap_or(repo_path);
    BUILD_FILES.contains(&name)
}

fn is_other_jvm_source(scoped: &str) -> bool {
    scoped
        .rsplit('/')
        .next()
        .and_then(|name| name.rsplit_once('.').map(|(_, ext)| ext))
        .is_some_and(|ext| OTHER_JVM_EXTENSIONS.contains(&ext))
}

fn is_consumer_source(repo_path: &str, frontend: Option<&BackendScope>) -> bool {
    if repo_path
        .split('/')
        .any(|part| part == "node_modules" || part == ".git")
    {
        return false;
    }
    let extension = repo_path
        .rsplit('/')
        .next()
        .and_then(|name| name.rsplit_once('.').map(|(_, ext)| ext))
        .map(|ext| ext.to_ascii_lowercase());
    if !extension.is_some_and(|ext| CONSUMER_EXTENSIONS.contains(&ext.as_str())) {
        return false;
    }
    match frontend {
        Some(scope) => scope.within(repo_path).is_some(),
        None => true,
    }
}

